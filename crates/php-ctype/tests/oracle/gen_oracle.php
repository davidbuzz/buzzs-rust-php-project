<?php
// Regenerates ../fixtures/oracle.txt:
//   php crates/php-ctype/tests/oracle/gen_oracle.php [path/to/php-src]
// Records (1) every ctype_* function over all bytes, byte pairs of interest,
// integers and other types, and (2) every ctype_* call made by the
// ext/ctype/tests/*.phpt FILE sections (calls are rewritten to go through
// the recorder of wrappers.php). The PHP binary running this script is the
// oracle; LC_CTYPE stays "C".
//
// Line format (tab separated):
//   <function> <arg> <result 0|1> <deprecation message or "-">
// where <arg> is s:<hex>, i:<int>, d:<float repr>, b:<0|1>, n, a, o:<class>, r.

$here = __DIR__;
$src = $argv[1] ?? dirname($here, 4) . '/modules/php-src';
$out = dirname($here) . '/fixtures/oracle.txt';
$tmp = sys_get_temp_dir() . '/php-ctype-oracle-' . getmypid();
@mkdir($tmp);
$log = "$tmp/log.txt";
@unlink($log);
putenv("CTYPE_ORACLE_LOG=$log");
$php = PHP_BINARY;
$wrappers = "$here/wrappers.php";

$custom = <<<'PHP'
<?php
$fns = ['ctype_alnum','ctype_alpha','ctype_cntrl','ctype_digit','ctype_graph','ctype_lower',
        'ctype_print','ctype_punct','ctype_space','ctype_upper','ctype_xdigit'];
$args = [];
for ($i = 0; $i < 256; $i++) { $args[] = chr($i); $args[] = $i; $args[] = $i - 128; }
foreach ([-129, -130, -1000, 256, 257, 1000, PHP_INT_MAX, PHP_INT_MIN, -300, 999999] as $i) $args[] = $i;
foreach (['', 'abc', 'ABC', 'aB1', '123', ' ', "\t\n", "a b", "1.5", "-1", "0x1F", "\0", "a\0",
          "\xe4", "abc\xff", '!@#', 'deadBEEF', 'ghi', "\x7f", "\x1f\x01"] as $s) $args[] = $s;
foreach ([1.0, 65.0, -1.5, 1e10, NAN, INF, true, false, null, [], [1], new stdClass] as $v) $args[] = $v;
foreach ($fns as $f) foreach ($args as $a) __ctype($f, $a);
PHP;
file_put_contents("$tmp/custom.php", $custom);

function run(string $php, string $file, string $wrappers) {
    shell_exec("$php -n -d extension=ctype -d error_reporting=-1 -d auto_prepend_file=" . escapeshellarg($wrappers) . ' '
        . escapeshellarg($file) . ' > /dev/null 2>&1');
}

run($php, "$tmp/custom.php", $wrappers);

foreach (glob("$src/ext/ctype/tests/*.phpt") as $phpt) {
    $text = file_get_contents($phpt);
    if (!preg_match('/^--FILE--\r?\n(.*?)^--[A-Z_]+--/sm', $text, $m)) continue;
    $code = preg_replace_callback('/(?<![\w$>:\'"])(ctype_[a-z]+)\s*\(/',
        fn($m) => "__ctype('$m[1]', ", $m[1]);
    // Dynamic calls such as $function($a) (001.phpt, 002.phpt).
    $code = preg_replace('/\$function\s*\(/', '__ctype($function, ', $code);
    $file = "$tmp/" . basename($phpt, '.phpt') . '.php';
    file_put_contents($file, $code);
    run($php, $file, $wrappers);
}

$lines = file($log, FILE_IGNORE_NEW_LINES);
$seen = [];
$res = ['# generated by gen_oracle.php with PHP ' . PHP_VERSION];
foreach ($lines as $l) {
    if (isset($seen[$l])) continue;
    $seen[$l] = true;
    $res[] = $l;
}
file_put_contents($out, implode("\n", $res) . "\n");
array_map('unlink', glob("$tmp/*"));
rmdir($tmp);
echo count($res) - 1, " records\n";

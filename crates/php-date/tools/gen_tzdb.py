#!/usr/bin/env python3
"""Generate php-date's bundled timezone tables from php-src's timelib sources.

Usage (from the repository root):

    python3 crates/php-date/tools/gen_tzdb.py modules/php-src/ext/date/lib

Produces:
  crates/php-date/src/tz/tzdb.bin      raw (slim) timezonedb blob, exactly as PHP embeds it
  crates/php-date/src/tz/generated.rs  index, version, abbreviation and fallback tables

PHP compiles parse_tz.c with TIMELIB_SUPPORT_SLIM_FILE defined, so the *slim*
variant of the database (the first block in timezonedb.h) is the one in use.
"""
import os
import re
import sys


def parse_tzdb(path):
    text = open(path, encoding="latin-1").read()
    slim = text.split("#ifdef TIMELIB_SUPPORT_SLIM_FILE", 1)[1].split("#else", 1)[0]
    idx_block = slim.split("timezonedb_idx_builtin", 1)[1].split("};", 1)[0]
    index = re.findall(r'\{\s*\(char\*\)\s*"([^"]+)"\s*,\s*0x([0-9A-Fa-f]+)\s*\}', idx_block)
    data_block = slim.split("timelib_timezone_db_data_builtin", 1)[1]
    m = re.match(r"\[(\d+)\]", data_block)
    size = int(m.group(1))
    body = data_block.split("{", 1)[1].split("};", 1)[0]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", body))
    assert len(data) == size, (len(data), size)
    version = re.search(r'timezonedb_builtin\s*=\s*\{\s*"([^"]+)"', text).group(1)
    return version, [(n, int(o, 16)) for n, o in index], data


def parse_map(path):
    out = []
    for line in open(path, encoding="latin-1"):
        m = re.match(r'\s*\{\s*"([^"]*)"\s*,\s*(-?\d+)\s*,\s*([-0-9 *]+?)\s*,\s*(NULL|"[^"]*")\s*\}', line)
        if not m:
            continue
        name, typ, off, tz = m.groups()
        off = int(eval(off, {"__builtins__": {}}))
        tz = None if tz == "NULL" else tz.strip('"')
        out.append((name, int(typ), off, tz))
    return out


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rs_opt(s):
    return "None" if s is None else "Some(" + rs_str(s) + ")"


def main():
    lib = sys.argv[1] if len(sys.argv) > 1 else "modules/php-src/ext/date/lib"
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "..", "src", "tz")
    version, index, data = parse_tzdb(os.path.join(lib, "timezonedb.h"))
    abbrs = parse_map(os.path.join(lib, "timezonemap.h"))
    fallback = parse_map(os.path.join(lib, "fallbackmap.h"))

    with open(os.path.join(out_dir, "tzdb.bin"), "wb") as f:
        f.write(data)

    lines = [
        "// @generated by crates/php-date/tools/gen_tzdb.py from php-src ext/date/lib.",
        "// Do not edit by hand.",
        "",
        "use super::AbbrEntry;",
        "",
        "/// Version string of the bundled database (`timezone_version_get()`).",
        f"pub(crate) const VERSION: &str = {rs_str(version)};",
        "",
        "/// Identifier index: name and byte offset into `tzdb.bin`, in PHP's order.",
        "#[rustfmt::skip]",
        f"pub(crate) static INDEX: [(&str, u32); {len(index)}] = [",
    ]
    for n, o in index:
        lines.append(f"    ({rs_str(n)}, 0x{o:06X}),")
    lines.append("];")
    lines.append("")
    for const, table, doc in (
        ("ABBREVIATIONS", abbrs, "Abbreviation table (timelib `timezonemap.h`), in PHP's order."),
        ("FALLBACK", fallback, "Offset fallback table (timelib `fallbackmap.h`)."),
    ):
        lines.append(f"/// {doc}")
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(crate) static {const}: [AbbrEntry; {len(table)}] = [")
        for name, typ, off, tz in table:
            lines.append(
                f"    AbbrEntry {{ name: {rs_str(name)}, dst: {'true' if typ else 'false'}, offset: {off}, tz_id: {rs_opt(tz)} }},"
            )
        lines.append("];")
        lines.append("")
    with open(os.path.join(out_dir, "generated.rs"), "w") as f:
        f.write("\n".join(lines))
    print(f"version {version}: {len(index)} zones, {len(data)} bytes, {len(abbrs)} abbreviations, {len(fallback)} fallbacks")


if __name__ == "__main__":
    main()

<?php
// Regenerates src/html_table.rs (the HTML 4.01 entity table used by
// FILTER_SANITIZE_FULL_SPECIAL_CHARS) from PHP's own translation table:
//   php crates/php-filter/tests/oracle/gen_html_table.php > crates/php-filter/src/html_table.rs
$t = get_html_translation_table(HTML_ENTITIES, ENT_QUOTES | ENT_HTML401, "UTF-8");
$rows = [];
foreach ($t as $ch => $ent) { $rows[mb_ord($ch, "UTF-8")] = substr($ent, 1, -1); }
ksort($rows);
$names = [];
foreach ($rows as $n) if ($n[0] != '#') $names[] = $n;
sort($names, SORT_STRING);
echo "//! Generated by `tests/oracle/gen_html_table.php` from PHP ", PHP_VERSION, ": the\n";
echo "//! HTML 4.01 entity table of `ext/standard/html_tables.h` (`ENT_HTML401`).\n\n";
echo "/// Code point to entity body (without `&` and `;`), sorted by code point.\n";
echo "pub(crate) static BY_CODEPOINT: [(u32, &str); ", count($rows), "] = [\n";
foreach ($rows as $cp => $n) printf("    (0x%04x, \"%s\"),\n", $cp, $n);
echo "];\n\n";
echo "/// The named entities of `ent_ht_html4`, sorted bytewise.\n";
echo "pub(crate) static NAMES: [&str; ", count($names), "] = [\n";
foreach (array_chunk($names, 8) as $chunk) echo "    ", implode(", ", array_map(fn($n) => "\"$n\"", $chunk)), ",\n";
echo "];\n";

<?php
// Regenerates ../fixtures/oracle.txt:
//   php crates/php-filter/tests/oracle/gen_oracle.php [path/to/php-src]
// Runs custom.php and every ext/filter/tests/**/*.phpt FILE section with
// the filter_* calls rewritten to go through the recorder of wrappers.php,
// using the PHP binary running this script as the oracle.

$here = __DIR__;
$src = $argv[1] ?? dirname($here, 4) . '/modules/php-src';
$out = dirname($here) . '/fixtures/oracle.txt';
$tmp = sys_get_temp_dir() . '/php-filter-oracle-' . getmypid();
@mkdir($tmp);
$log = "$tmp/log.txt";
@unlink($log);
putenv("FILTER_ORACLE_LOG=$log");
$php = PHP_BINARY;
$wrappers = "$here/wrappers.php";

function rewrite(string $code): string {
    return preg_replace(
        '/(?<![\w$>:\\\\\'"])(filter_var_array|filter_var|filter_input_array|filter_input|filter_has_var|filter_id|filter_list)\s*\(/',
        "__filter_rec('\$1', ", $code);
}

function run(string $php, string $file, array $ini, string $wrappers) {
    $args = '-n -d error_reporting=-1 -d display_errors=0 -d auto_prepend_file=' . escapeshellarg($wrappers);
    foreach ($ini as $k => $v) $args .= ' -d ' . escapeshellarg("$k=$v");
    shell_exec("$php $args " . escapeshellarg($file) . ' > /dev/null 2>&1');
}

run($php, "$here/custom.php", ['precision' => 14, 'serialize_precision' => -1], $wrappers);

$phpts = array_merge(glob("$src/ext/filter/tests/*.phpt"), glob("$src/ext/filter/tests/*/*.phpt"));
foreach (glob("$src/ext/filter/tests/*.inc") as $inc) {
    file_put_contents("$tmp/" . basename($inc), rewrite(file_get_contents($inc)));
}
foreach ($phpts as $phpt) {
    $text = file_get_contents($phpt);
    if (!preg_match('/^--FILE--\r?\n(.*?)^--[A-Z_]+--/sm', $text, $m)) continue;
    $ini = ['precision' => 14, 'serialize_precision' => -1];
    if (preg_match('/^--INI--\r?\n(.*?)^--[A-Z_]+--/sm', $text, $im)) {
        foreach (preg_split('/\r?\n/', trim($im[1])) as $line) {
            if (strpos($line, '=') !== false) {
                [$k, $v] = explode('=', $line, 2);
                $ini[trim($k)] = trim($v);
            }
        }
    }
    unset($ini['memory_limit']);
    $file = "$tmp/" . basename($phpt, '.phpt') . '.php';
    file_put_contents($file, rewrite($m[1]));
    run($php, $file, $ini, $wrappers);
}

$lines = file($log, FILE_IGNORE_NEW_LINES);
$seen = [];
$res = ['# generated by gen_oracle.php with PHP ' . PHP_VERSION];
foreach ($lines as $l) {
    if (isset($seen[$l]) || strlen($l) > 65536) continue;
    $seen[$l] = true;
    $res[] = $l;
}
file_put_contents($out, implode("\n", $res) . "\n");
array_map('unlink', glob("$tmp/*"));
rmdir($tmp);
echo count($res) - 1, " records\n";

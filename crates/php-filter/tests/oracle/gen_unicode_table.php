<?php
// Regenerates src/unicode_table.rs: the code points >= 0x80 matched by
// [\pL\pN] under /iu, i.e. the non-ASCII characters that the
// FILTER_FLAG_EMAIL_UNICODE regex accepts in local parts. Uses the PCRE2
// library of the PHP binary running this script:
//   php crates/php-filter/tests/oracle/gen_unicode_table.php > crates/php-filter/src/unicode_table.rs
$ranges = []; $start = -1; $prev = -2;
for ($cp = 0x80; $cp <= 0x10FFFF; $cp++) {
    if ($cp >= 0xD800 && $cp <= 0xDFFF) continue;
    if (preg_match('/^[\pL\pN]$/iu', mb_chr($cp, 'UTF-8'))) {
        if ($cp != $prev + 1) { if ($start >= 0) $ranges[] = [$start, $prev]; $start = $cp; }
        $prev = $cp;
    }
}
$ranges[] = [$start, $prev];
echo "//! Generated by `tests/oracle/gen_unicode_table.php` (PHP ", PHP_VERSION, ", PCRE2 ", PCRE_VERSION, "):\n";
echo "//! the non-ASCII code points of `[\\pL\\pN]` (Unicode letters and numbers).\n\n";
echo "/// Inclusive code point ranges, sorted.\n";
echo "pub(crate) static LETTER_OR_NUMBER: [(u32, u32); ", count($ranges), "] = [\n";
foreach (array_chunk($ranges, 4) as $chunk) {
    echo "   ";
    foreach ($chunk as [$a, $b]) printf(" (0x%04x, 0x%04x),", $a, $b);
    echo "\n";
}
echo "];\n";

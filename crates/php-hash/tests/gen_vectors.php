<?php
// Usage: php crates/php-hash/tests/gen_vectors.php crates/php-hash/tests/vectors/mod.rs
// Generates tests/vectors.rs for php-hash from the C implementation.
$inputs = ["", "a", "abc", "message digest", "The quick brown fox jumps over the lazy dog",
  str_repeat("0123456789", 13), str_repeat("\xff\x00\x80abc", 300)];
$out = "// buzzs-rust-php-project - Copyright (c) 2025-2026 David Buzz <davidbuzz@gmail.com>\n// Licensed under the BSD-3-Clause, the license PHP master uses; see LICENSE.\n// @generated by a PHP oracle script from /usr/bin/php8.5 " . PHP_VERSION . "; do not edit.\n#![allow(clippy::doc_markdown, clippy::unreadable_literal)]\n\n";
$out .= "pub const INPUTS: &[&[u8]] = &[\n";
foreach ($inputs as $i) $out .= "    b\"" . esc($i) . "\",\n";
$out .= "];\n\n";
function esc($s) { $r = ""; for ($k=0;$k<strlen($s);$k++){ $c=ord($s[$k]); $r .= ($c>=0x20&&$c<0x7f&&$c!=0x22&&$c!=0x5c)?chr($c):sprintf("\\x%02x",$c);} return $r; }
$out .= "/// (algo, [hex digest per input])\npub const DIGESTS: &[(&str, &[&str])] = &[\n";
foreach (hash_algos() as $a) {
  $out .= "    (\"$a\", &[";
  foreach ($inputs as $i) $out .= "\"" . hash($a, $i) . "\", ";
  $out .= "]),\n";
}
$out .= "];\n\n";
// incremental with odd chunking
$out .= "/// (algo, hex) of the last input fed in chunks of 1,2,3,...\npub const CHUNKED: &[(&str, &str)] = &[\n";
$big = $inputs[6];
foreach (hash_algos() as $a) {
  $c = hash_init($a); $p = 0; $n = 1;
  while ($p < strlen($big)) { hash_update($c, substr($big, $p, $n)); $p += $n; $n = $n % 70 + 1; }
  $out .= "    (\"$a\", \"" . hash_final($c) . "\"),\n";
}
$out .= "];\n\n";
$out .= "pub const HMAC: &[(&str, &str, &str)] = &[\n";
foreach (hash_hmac_algos() as $a) {
  $out .= "    (\"$a\", \"" . hash_hmac($a, "data", "key") . "\", \"" . hash_hmac($a, $big, str_repeat("k", 300)) . "\"),\n";
}
$out .= "];\n\n";
$out .= "pub const SEEDED: &[(&str, i64, &str)] = &[\n";
foreach (["murmur3a","murmur3c","murmur3f","xxh32","xxh64","xxh3","xxh128"] as $a)
  foreach ([0, 1, 42, -1, 0x7fffffff, PHP_INT_MIN] as $seed)
    foreach ([2, 6] as $ii)
      $out .= "    (\"$a\", " . ($seed == PHP_INT_MIN ? "i64::MIN" : $seed) . ", \"" . hash($a, $inputs[$ii], false, ["seed" => $seed]) . "\"),\n";
$out .= "];\n\n";
$secret = str_repeat("secret-0123456789", 12);
$out .= "pub const SECRET: &[u8] = b\"" . esc($secret) . "\";\n";
$out .= "pub const SECRETED: &[(&str, &str, &str)] = &[\n";
foreach (["xxh3","xxh128"] as $a)
  $out .= "    (\"$a\", \"" . hash($a, $inputs[2], false, ["secret"=>$secret]) . "\", \"" . hash($a, $inputs[6], false, ["secret"=>$secret]) . "\"),\n";
$out .= "];\n\n";
// serialization: init + update "I can't remember anything"
$out .= "/// (algo, serialized state as php serialize() of __serialize()[2], magic)\npub const SERIALIZED: &[(&str, &[u8], i64)] = &[\n";
foreach (hash_algos() as $a) {
  if ($a == "xxh3" || $a == "xxh128") continue;
  foreach (["I can't remember anything", $big] as $d) {
  $c = hash_init($a); hash_update($c, $d); $s = $c->__serialize();
  $out .= "    (\"$a\", b\"" . esc(serialize($s[2])) . "\", {$s[3]}),\n";
  }
}
$out .= "];\n\n";
$out .= "/// (algo, serialized state after chunked updates of the first 1003 bytes of INPUTS[6])\npub const SERIALIZED_CHUNKED: &[(&str, &[u8])] = &[\n";
foreach (hash_algos() as $a) {
  if ($a == "xxh3" || $a == "xxh128") continue;
  $c = hash_init($a); $p = 0; $n = 1; $d = substr($big, 0, 1003);
  while ($p < strlen($d)) { hash_update($c, substr($d, $p, $n)); $p += $n; $n = $n % 37 + 1; }
  $out .= "    (\"$a\", b\"" . esc(serialize($c->__serialize()[2])) . "\"),\n";
}
$out .= "];\n\n";
$out .= "pub const PBKDF2: &[(&str, i64, i64, bool, &str)] = &[\n";
foreach ([["sha1",1,0,false],["sha256",1000,0,false],["sha256",2,7,false],["md5",3,33,true],["sha512",5,100,false],["whirlpool",2,0,true]] as [$a,$it,$len,$raw]) {
  $r = hash_pbkdf2($a, "password", "salt", $it, $len, $raw);
  $out .= "    (\"$a\", $it, $len, " . ($raw?"true":"false") . ", \"" . bin2hex($r) . "\"),\n";
}
$out .= "];\n\n";
$out .= "pub const HKDF: &[(&str, i64, &str, &str, &str)] = &[\n";
foreach ([["sha256",0,"",""],["sha256",42,"info","salt"],["md5",100,"",str_repeat("s",100)],["sha512",255,"x","y"]] as [$a,$l,$info,$salt])
  $out .= "    (\"$a\", $l, \"$info\", \"$salt\", \"" . bin2hex(hash_hkdf($a, "input key", $l, $info, $salt)) . "\"),\n";
$out .= "];\n";
file_put_contents($argv[1], $out);

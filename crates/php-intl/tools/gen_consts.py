#!/usr/bin/env python3
"""Generate src/constants.rs: every ext/intl constant (global and class).

Names and order come from the php-src master stubs; values come from
tools/consts83.tsv (dumped from /usr/bin/php 8.3 + ICU 74.2 with
`php -d memory_limit=1G tools/dump_consts.php`) or, for constants that 8.3
lacks, from the MASTER_ONLY table below (ICU 74 header values).
Run manually: python3 tools/gen_consts.py > src/constants.rs
"""
import glob
import re

ROOT = '/home/buzz/phprust/modules/php-src/ext/intl/'
HERE = '/home/buzz/phprust/crates/php-intl/tools/'

MASTER_ONLY = {
    ('IntlDateFormatter', 'PATTERN'): '-2',
    ('IntlDateFormatter', 'PROLEPTIC_GREGORIAN'): '-16',
    ('NumberFormatter', 'DECIMAL_COMPACT_SHORT'): '14',
    ('NumberFormatter', 'DECIMAL_COMPACT_LONG'): '15',
    ('NumberFormatter', 'CURRENCY_ISO'): '10',
    ('NumberFormatter', 'CURRENCY_PLURAL'): '11',
    ('NumberFormatter', 'CASH_CURRENCY'): '13',
    ('NumberFormatter', 'CURRENCY_STANDARD'): '16',
    ('NumberFormatter', 'ROUND_TOWARD_ZERO'): '2',
    ('NumberFormatter', 'ROUND_AWAY_FROM_ZERO'): '3',
    ('NumberFormatter', 'ROUND_HALFODD'): '8',
    ('IntlListFormatter', 'TYPE_AND'): '0',
    ('IntlListFormatter', 'TYPE_OR'): '1',
    ('IntlListFormatter', 'TYPE_UNITS'): '2',
    ('IntlListFormatter', 'WIDTH_WIDE'): '0',
    ('IntlListFormatter', 'WIDTH_SHORT'): '1',
    ('IntlListFormatter', 'WIDTH_NARROW'): '2',
    ('IntlNumberRangeFormatter', 'COLLAPSE_AUTO'): '0',
    ('IntlNumberRangeFormatter', 'COLLAPSE_NONE'): '1',
    ('IntlNumberRangeFormatter', 'COLLAPSE_UNIT'): '2',
    ('IntlNumberRangeFormatter', 'COLLAPSE_ALL'): '3',
    ('IntlNumberRangeFormatter', 'IDENTITY_FALLBACK_SINGLE_VALUE'): '0',
    ('IntlNumberRangeFormatter', 'IDENTITY_FALLBACK_APPROXIMATELY_OR_SINGLE_VALUE'): '1',
    ('IntlNumberRangeFormatter', 'IDENTITY_FALLBACK_APPROXIMATELY'): '2',
    ('IntlNumberRangeFormatter', 'IDENTITY_FALLBACK_RANGE'): '3',
    ('Spoofchecker', 'IGNORE_SPACE'): '1',
    ('Spoofchecker', 'CASE_INSENSITIVE'): '2',
    ('Spoofchecker', 'ADD_CASE_MAPPINGS'): '4',
    ('Spoofchecker', 'SIMPLE_CASE_INSENSITIVE'): '6',
    ('Spoofchecker', 'LTR'): '0',
    ('Spoofchecker', 'RTL'): '1',
    ('IntlChar', 'PROPERTY_IDS_UNARY_OPERATOR'): '72',
    ('IntlChar', 'PROPERTY_ID_COMPAT_MATH_START'): '73',
    ('IntlChar', 'PROPERTY_ID_COMPAT_MATH_CONTINUE'): '74',
}

values = {}
for line in open(HERE + 'consts83.tsv'):
    c, n, v = line.rstrip('\n').split('\t')
    values[(c, n)] = v

order = []
seen = set()
for f in sorted(glob.glob(ROOT + '**/*.stub.php', recursive=True)):
    cls = 'global'
    for ln in open(f):
        m = re.match(r'\s*(?:final\s+|abstract\s+)?(?:class|enum|interface)\s+(\w+)', ln)
        if m:
            cls = m.group(1)
        if re.match(r'^}', ln):
            cls = 'global'
        m = re.match(r'\s*(?:public\s+)?const\s+(?:\w+\s+)?(\w+)\s*=', ln)
        if m and (cls, m.group(1)) not in seen:
            seen.add((cls, m.group(1)))
            order.append((cls, m.group(1)))

def rust_value(c, n, v):
    if (c, n) == ('global', 'INTL_ICU_VERSION'):
        return 'ConstValue::Str(crate::common::ICU_VERSION)'
    if (c, n) == ('global', 'INTL_ICU_DATA_VERSION'):
        return 'ConstValue::Str(crate::common::ICU_DATA_VERSION)'
    if v == 'NULL' or v == 'null':
        return 'ConstValue::Null'
    if v.startswith("'"):
        return 'ConstValue::Str("%s")' % v.strip("'")
    if re.match(r'^-?\d+\.\d+$', v):
        return 'ConstValue::Float(%s)' % v
    return 'ConstValue::Int(%s)' % v

groups = {}
for c, n in order:
    v = values.get((c, n), MASTER_ONLY.get((c, n)))
    if v is None:
        raise SystemExit('no value for %s::%s' % (c, n))
    groups.setdefault(c, []).append((n, rust_value(c, n, v)))
missing = [k for k in values if k not in seen]
if missing:
    raise SystemExit('8.3 constants missing from the stubs: %r' % missing)

print('//! Every ext/intl constant (php-src master names and order, ICU 74 values).')
print('//! Generated by `tools/gen_consts.py`; do not edit by hand.')
print('#![allow(clippy::unreadable_literal)]')
print()
print('/// A constant value.')
print('#[derive(Debug, Clone, Copy, PartialEq)]')
print('pub enum ConstValue {')
print('    /// `int`')
print('    Int(i64),')
print('    /// `float`')
print('    Float(f64),')
print('    /// `string`')
print('    Str(&\'static str),')
print('    /// `null`')
print('    Null,')
print('}')
print()
print('/// Global constants (`define`d by the extension).')
print('pub const GLOBAL: &[(&str, ConstValue)] = &[')
for n, v in groups.pop('global'):
    print('    ("%s", %s),' % (n, v))
print('];')
print()
print('/// Class constants, per class.')
print('pub const CLASSES: &[(&str, &[(&str, ConstValue)])] = &[')
for c, items in groups.items():
    print('    (')
    print('        "%s",' % c)
    print('        &[')
    for n, v in items:
        print('            ("%s", %s),' % (n, v))
    print('        ],')
    print('    ),')
print('];')
print()
print('''/// The constants of `class` (exact class name), if it declares any.
#[must_use]
pub fn class_constants(class: &str) -> Option<&'static [(&'static str, ConstValue)]> {
    CLASSES.iter().find(|(c, _)| *c == class).map(|(_, v)| *v)
}

/// Looks up `class::name` (`class` = `None` for a global constant).
#[must_use]
pub fn lookup(class: Option<&str>, name: &str) -> Option<ConstValue> {
    let table = match class {
        None => GLOBAL,
        Some(c) => class_constants(c)?,
    };
    table.iter().find(|(n, _)| *n == name).map(|(_, v)| *v)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookups() {
        assert_eq!(lookup(None, "U_ZERO_ERROR"), Some(ConstValue::Int(0)));
        assert_eq!(
            lookup(Some("IntlDateFormatter"), "PROLEPTIC_GREGORIAN"),
            Some(ConstValue::Int(-16))
        );
        assert_eq!(lookup(Some("Locale"), "DEFAULT_LOCALE"), Some(ConstValue::Null));
        assert!(class_constants("Collator").is_some_and(|c| c.len() > 20));
    }
}''')

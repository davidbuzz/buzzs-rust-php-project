<?php
// Regenerates ../fixtures/locations.txt from php-src master's error-location
// tests (json_last_error_msg_error_location_*.phpt, json_validate_00[24].phpt):
//   php crates/php-json/tests/oracle/gen_locations.php [path/to/php-src]
// The calls are captured by running the FILE sections with a logging
// json_validate() wrapper; the expected (master) json_last_error() /
// json_last_error_msg() pairs come from the EXPECT sections, in order.
// Records: L <file> <hex json> <depth> <flags> <code> <hex msg>; the calls of
// one file must be replayed in order on one state.

$here = __DIR__;
$src = $argv[1] ?? dirname($here, 4) . '/modules/php-src';
$out = dirname($here) . '/fixtures/locations.txt';
$tmp = sys_get_temp_dir() . '/php-json-locations-' . getmypid();
@mkdir($tmp);
$wrap = <<<'PHP'
<?php
function __jv(string $json, int $depth = 512, int $flags = 0) {
    file_put_contents(getenv('JSON_LOC_LOG'), bin2hex($json) . "\t$depth\t$flags\n", FILE_APPEND);
    return json_validate($json, $depth, $flags);
}
PHP;
file_put_contents("$tmp/wrap.php", $wrap);
$inc = file_get_contents("$src/ext/json/tests/json_validate_requires.inc");
file_put_contents("$tmp/json_validate_requires.inc", preg_replace('/\bjson_validate\s*\(/', '__jv(', $inc));

$records = [];
$files = array_merge(glob("$src/ext/json/tests/json_last_error_msg_error_location_*.phpt"),
    ["$src/ext/json/tests/json_validate_002.phpt", "$src/ext/json/tests/json_validate_004.phpt"]);
foreach ($files as $phpt) {
    $name = basename($phpt, '.phpt');
    $text = file_get_contents($phpt);
    preg_match('/^--FILE--\r?\n(.*?)^--[A-Z_]+--/sm', $text, $m);
    preg_match('/^--EXPECTF?--\r?\n(.*)\z/sm', $text, $e);
    $code = str_replace('require_once("json_validate_requires.inc")',
        'require_once(' . var_export("$tmp/json_validate_requires.inc", true) . ')', $m[1]);
    file_put_contents("$tmp/$name.php", $code);
    $log = "$tmp/$name.log";
    @unlink($log);
    putenv("JSON_LOC_LOG=$log");
    shell_exec(PHP_BINARY . ' -n -d auto_prepend_file=' . escapeshellarg("$tmp/wrap.php") . ' ' . escapeshellarg("$tmp/$name.php") . ' > /dev/null 2>&1');
    $calls = file($log, FILE_IGNORE_NEW_LINES);
    preg_match_all('/^int\((\d+)\)\r?\nstring\(\d+\) "(.*)"$/m', $e[1], $pairs, PREG_SET_ORDER);
    if (count($pairs) !== count($calls)) {
        fwrite(STDERR, "$name: " . count($calls) . " calls but " . count($pairs) . " results, skipped\n");
        continue;
    }
    foreach ($calls as $i => $c) {
        $records[] = "L\t$name\t$c\t{$pairs[$i][1]}\t" . bin2hex($pairs[$i][2]);
    }
}
file_put_contents($out, "# generated by gen_locations.php\n" . implode("\n", $records) . "\n");
echo count($records), " records written to $out\n";

<?php
// Regenerates ../fixtures/oracle.txt:
//   php crates/php-json/tests/oracle/gen_oracle.php [path/to/php-src]
// Runs custom.php and every ext/json/tests/*.phpt FILE section with the
// logging wrappers of wrappers.php in place of json_encode/json_decode/
// json_validate, using the PHP binary running this script as the oracle.

$here = __DIR__;
$src = $argv[1] ?? dirname($here, 4) . '/modules/php-src';
$out = dirname($here) . '/fixtures/oracle.txt';
@mkdir(dirname($out));
$tmp = sys_get_temp_dir() . '/php-json-oracle-' . getmypid();
@mkdir($tmp);
$log = "$tmp/log.txt";
@unlink($log);
putenv("JSON_ORACLE_LOG=$log");
$php = PHP_BINARY;

function run(string $php, string $file, array $ini, string $wrappers) {
    $args = '-n -d auto_prepend_file=' . escapeshellarg($wrappers);
    foreach ($ini as $k => $v) $args .= ' -d ' . escapeshellarg("$k=$v");
    shell_exec("$php $args " . escapeshellarg($file) . ' > /dev/null 2>&1');
}

run($php, "$here/custom.php", ['serialize_precision' => -1, 'precision' => 14], "$here/wrappers.php");

foreach (glob("$src/ext/json/tests/*.phpt") as $phpt) {
    $text = file_get_contents($phpt);
    if (!preg_match('/^--FILE--\r?\n(.*?)^--[A-Z_]+--/sm', $text, $m)) continue;
    $code = $m[1];
    $ini = ['serialize_precision' => -1, 'precision' => 14];
    if (preg_match('/^--INI--\r?\n(.*?)^--[A-Z_]+--/sm', $text, $im)) {
        foreach (preg_split('/\r?\n/', trim($im[1])) as $line) {
            if (strpos($line, '=') !== false) {
                [$k, $v] = explode('=', $line, 2);
                $ini[trim($k)] = trim($v);
            }
        }
    }
    $code = preg_replace('/\bjson_encode\s*\(/', '__je(', $code);
    $code = preg_replace('/\bjson_decode\s*\(/', '__jd(', $code);
    $code = preg_replace('/\bjson_validate\s*\(/', '__jv(', $code);
    $code = str_replace('require_once("json_validate_requires.inc")',
        'require_once(' . var_export("$tmp/json_validate_requires.inc", true) . ')', $code);
    $inc = @file_get_contents("$src/ext/json/tests/json_validate_requires.inc");
    file_put_contents("$tmp/json_validate_requires.inc",
        preg_replace('/\bjson_validate\s*\(/', '__jv(', (string)$inc));
    $file = "$tmp/" . basename($phpt, '.phpt') . '.php';
    file_put_contents($file, $code);
    unset($ini['memory_limit']);
    run($php, $file, $ini, "$here/wrappers.php");
}

// Deduplicate while keeping order.
$lines = file($log, FILE_IGNORE_NEW_LINES);
$seen = [];
$res = [];
foreach ($lines as $l) {
    if (isset($seen[$l]) || strlen($l) > 16384) continue;
    $seen[$l] = true;
    $res[] = $l;
}
file_put_contents($out, "# generated by gen_oracle.php with PHP " . PHP_VERSION . "\n" . implode("\n", $res) . "\n");
echo count($res), " records written to $out\n";

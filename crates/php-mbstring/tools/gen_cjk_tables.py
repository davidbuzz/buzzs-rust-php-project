#!/usr/bin/env python3
"""Generate src/tables/cjk/*.rs from libmbfl's CJK headers and sources.

Every `const` integer array (1-D, 2-D, or array of pointers to other arrays)
and every integer scalar constant (including `sizeof`-based lengths, which are
evaluated here) found in the listed C files is emitted as a Rust `pub static`
(arrays) or `pub const` (scalars, as `i32`), with the C name upper-cased.

Usage: python3 tools/gen_cjk_tables.py [path/to/php-src]
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "modules" / "php-src"
FILTERS = SRC / "ext/mbstring/libmbfl/filters"
OUT_DIR = HERE.parent / "src/tables/cjk"

# (output module, source file, doc)
MODULES = [
    ("jis", "unicode_table_jis.h", "JIS X 0208 / JIS X 0212 tables"),
    ("jis2004", "unicode_table_jis2004.h", "JIS X 0213:2004 tables"),
    ("cp932_ext", "unicode_table_cp932_ext.h", "CP932 extension tables (NEC/IBM)"),
    ("cp932", "cp932_table.h", "CP932 extension to EUC-JP mapping"),
    ("big5", "unicode_table_big5.h", "Big5 tables"),
    ("cns11643", "unicode_table_cns11643.h", "CNS 11643 tables (EUC-TW)"),
    ("cp936", "unicode_table_cp936.h", "CP936 (GBK) tables"),
    ("gb18030", "unicode_table_gb18030.h", "GB18030 tables"),
    ("gb2312", "unicode_table_gb2312.h", "GB2312 tables"),
    ("uhc", "unicode_table_uhc.h", "UHC (CP949) tables"),
    ("emoji", "emoji2uni.h", "Japanese mobile carrier emoji tables"),
    ("sjis_mac", "sjis_mac2uni.h", "`MacJapanese` tables"),
    ("misc", "mbfilter_cjk.c", "Small tables defined in `mbfilter_cjk.c`"),
    ("utf8_mobile", "mbfilter_utf8.c", "Tables for the mobile UTF-8 variants (`mbfilter_utf8.c`)"),
]

# Arrays not to emit for a module (already provided elsewhere).
EXCLUDE = {
    "utf8_mobile": {"mblen_table_utf8", "nflags_code_kddi", "nflags_code_sb"},
}

CTYPES = {
    "unsigned short": "u16",
    "unsigned int": "u32",
    "unsigned char": "u8",
    "int": "i32",
}

ARRAY_RE = re.compile(
    r"(?:static\s+)?const\s+(unsigned\s+short|unsigned\s+int|unsigned\s+char|int)\s+"
    r"(\*?)\s*(\w+)\s*\[\s*(\w*)\s*\](?:\s*\[\s*(\d+)\s*\])?\s*=\s*\{(.*?)\}\s*;",
    re.S,
)
SCALAR_RE = re.compile(
    r"^(?:static\s+)?(?:const\s+)?(?:int|unsigned\s+short)\s+(\w+)\s*=\s*([^;{]+);",
    re.M,
)


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def parse_int(tok):
    tok = tok.strip()
    if re.fullmatch(r"0[xX][0-9A-Fa-f]+[uUlL]*", tok):
        return int(tok.rstrip("uUlL"), 16)
    if re.fullmatch(r"-?\d+[uUlL]*", tok):
        return int(tok.rstrip("uUlL"))
    raise ValueError(f"not an integer literal: {tok!r}")


def rust_name(name):
    return name.upper()


def fmt_val(v, rtype):
    if rtype == "i32":
        return f"0x{v:04X}" if v >= 0 else str(v)
    width = {"u8": 2, "u16": 4, "u32": 4}[rtype]
    return f"0x{v:0{width}X}"


def gen_module(mod, fname, doc):
    text = strip_comments((FILTERS / fname).read_text(encoding="latin-1"))
    out = [
        f"//! {doc}.\n",
        f"//! GENERATED by `tools/gen_cjk_tables.py` from `libmbfl/filters/{fname}`; do not edit.\n\n",
        "#![allow(clippy::unreadable_literal, missing_docs)]\n\n",
    ]
    lengths = {}  # C name -> (element count, element size in bytes, row width)
    elem_size = {"u16": 2, "u32": 4, "u8": 1, "i32": 4}
    seen = set()
    for m in ARRAY_RE.finditer(text):
        ctype, ptr, name, dim1, dim2, body = m.groups()
        ctype = " ".join(ctype.split())
        rtype = CTYPES[ctype]
        if name in seen or name in EXCLUDE.get(mod, ()):
            continue
        seen.add(name)
        out.append("#[rustfmt::skip]\n")
        if ptr:
            items = [t.strip() for t in body.split(",") if t.strip()]
            out.append(f"pub static {rust_name(name)}: [&[{rtype}]; {len(items)}] = [\n")
            for it in items:
                out.append(f"    &{rust_name(it)},\n")
            out.append("];\n\n")
            lengths[name] = (len(items), 8, 1)
            continue
        if dim2:
            n2 = int(dim2)
            rows = re.findall(r"\{([^{}]*)\}", body)
            vals = [[parse_int(t) for t in r.split(",") if t.strip()] for r in rows]
            for r in vals:
                if len(r) != n2:
                    r.extend([0] * (n2 - len(r)))
            if dim1:
                assert int(dim1) == len(vals), name
            out.append(f"pub static {rust_name(name)}: [[{rtype}; {n2}]; {len(vals)}] = [\n")
            for r in vals:
                out.append("    [" + ", ".join(fmt_val(v, rtype) for v in r) + "],\n")
            out.append("];\n\n")
            lengths[name] = (len(vals) * n2, elem_size[rtype], n2)
            continue
        vals = [parse_int(t) for t in body.split(",") if t.strip()]
        if rtype != "i32":
            # C converts negative initialisers modulo 2^N (sjis_mobile_decode_tbl1)
            bits = {"u8": 8, "u16": 16, "u32": 32}[rtype]
            vals = [v % (1 << bits) for v in vals]
        if dim1:
            n1 = int(dim1)
            assert len(vals) <= n1, name
            vals.extend([0] * (n1 - len(vals)))
        out.append(f"pub static {rust_name(name)}: [{rtype}; {len(vals)}] = [\n")
        width = 8 if rtype != "u8" else 16
        for i in range(0, len(vals), width):
            out.append("    " + ", ".join(fmt_val(v, rtype) for v in vals[i : i + width]) + ",\n")
        out.append("];\n\n")
        lengths[name] = (len(vals), elem_size[rtype], 1)

    sizes = {"unsigned short": 2, "unsigned int": 4, "int": 4, "unsigned char": 1}

    def eval_expr(expr):
        e = " ".join(expr.split())

        def sizeof(mm):
            arg = " ".join(mm.group(1).split())
            if arg in sizes:
                return str(sizes[arg])
            n, esz, _ = lengths[arg]
            return str(n * esz)

        e = re.sub(r"sizeof\s*\(\s*([\w ]+?)\s*\)", sizeof, e)
        e = re.sub(r"0[xX][0-9A-Fa-f]+", lambda mm: str(int(mm.group(0), 16)), e)
        e = e.replace("/", "//")
        if not re.fullmatch(r"[\d\s+\-*/()]+", e):
            raise ValueError(f"cannot evaluate {expr!r}")
        return eval(e)  # noqa: S307 - arithmetic on literals only

    for m in SCALAR_RE.finditer(text):
        name, expr = m.groups()
        try:
            v = eval_expr(expr)
        except (ValueError, KeyError):
            continue
        out.append(f"pub const {rust_name(name)}: i32 = {fmt_val(v, 'i32')};\n")

    path = OUT_DIR / f"{mod}.rs"
    path.write_text("".join(out).rstrip("\n") + "\n")
    print(f"wrote {path}")


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for mod, fname, doc in MODULES:
        gen_module(mod, fname, doc)
    lines = [
        "//! CJK conversion tables.\n",
        "//! GENERATED by `tools/gen_cjk_tables.py` from libmbfl's sources; do not edit.\n\n",
    ]
    for mod, fname, doc in MODULES:
        lines.append(f"pub mod {mod};\n")
    (OUT_DIR / "mod.rs").write_text("".join(lines))


main()

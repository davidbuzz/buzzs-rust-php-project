#!/usr/bin/env python3
"""Generate src/tables/html_entities.rs from libmbfl's html_entities.c.

Usage: python3 tools/gen_html_entities.py [path/to/php-src]
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "modules" / "php-src"
C_FILE = SRC / "ext/mbstring/libmbfl/filters/html_entities.c"
OUT = HERE.parent / "src/tables/html_entities.rs"

text = C_FILE.read_text()
body = re.search(r"mbfl_html_entity_list\[\] = \{(.*?)\};", text, re.S).group(1)
entries = re.findall(r'\{\s*"(\w+)"\s*,\s*(\d+)\s*\}', body)

out = [
    "//! HTML named entities (`mbfl_html_entity_list`), in libmbfl's order\n",
    "//! (lookups take the first match).\n",
    "//! GENERATED by `tools/gen_html_entities.py` from `libmbfl/filters/html_entities.c`; do not edit.\n\n",
    "/// `(name, code point)` pairs.\n",
    "#[rustfmt::skip]\n",
    f"pub static HTML_ENTITY_LIST: [(&str, u32); {len(entries)}] = [\n",
]
for name, code in entries:
    out.append(f'    ("{name}", {code}),\n')
out.append("];\n")

OUT.write_text("".join(out))
print(f"wrote {OUT} ({len(entries)} entities)")

#!/usr/bin/env python3
"""Generate src/tables/singlebyte.rs from libmbfl's mbfilter_singlebyte.c.

Usage: python3 tools/gen_singlebyte.py [path/to/php-src]
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "modules" / "php-src"
C_FILE = SRC / "ext/mbstring/libmbfl/filters/mbfilter_singlebyte.c"
OUT = HERE.parent / "src/tables/singlebyte.rs"

text = C_FILE.read_text()
arrays = re.findall(
    r"static const unsigned (short|char) (\w+)\[\] = \{(.*?)\};", text, re.S
)

out = [
    "//! Single-byte encoding tables.\n",
    "//! GENERATED by `tools/gen_singlebyte.py` from `libmbfl/filters/mbfilter_singlebyte.c`; do not edit.\n\n",
]
for ctype, name, body in arrays:
    vals = [int(v, 16) for v in re.findall(r"0[xX][0-9A-Fa-f]+", body)]
    rtype = "u16" if ctype == "short" else "u8"
    out.append("#[rustfmt::skip]\n")
    out.append(f"pub static {name.upper()}: [{rtype}; {len(vals)}] = [\n")
    width = 8
    for i in range(0, len(vals), width):
        chunk = vals[i : i + width]
        fmt = "0x{:04X}" if rtype == "u16" else "0x{:02X}"
        out.append("    " + ", ".join(fmt.format(v) for v in chunk) + ",\n")
    out.append("];\n\n")

OUT.write_text("".join(out).rstrip("\n") + "\n")
print(f"wrote {OUT} ({len(arrays)} tables)")

#!/usr/bin/env python3
"""Generate the Unicode property / case-mapping / width / rare-codepoint tables.

Sources (php-src):
  ext/mbstring/unicode_data.h          -> src/tables/unicode_data.rs
  ext/mbstring/libmbfl/mbfl/eaw_table.h -> src/tables/eaw.rs
  ext/mbstring/rare_cp_bitvec.h        -> src/tables/rare_cp.rs
  ext/mbstring/libmbfl/filters/unicode_prop.h -> src/tables/qencode.rs

Usage: python3 tools/gen_unicode_tables.py [path/to/php-src]
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "modules" / "php-src"
MB = SRC / "ext/mbstring"
OUT = HERE.parent / "src/tables"

CTYPES = {
    "unsigned short": "u16",
    "short": "i16",
    "unsigned int": "u32",
    "unsigned": "u32",
    "uint32_t": "u32",
}


def header(src):
    return (
        f"//! GENERATED by `tools/gen_unicode_tables.py` from `{src}`; do not edit.\n\n"
    )


def emit_array(name, rtype, vals, per_line=8):
    lines = ["#[rustfmt::skip]\n", f"pub static {name}: [{rtype}; {len(vals)}] = [\n"]
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(str(v) if rtype == "i16" else hex(v) for v in vals[i:i + per_line]) + ",\n")
    lines.append("];\n\n")
    return "".join(lines)


def parse_int(tok):
    tok = tok.strip().rstrip("uUlL")
    return int(tok, 0)


def gen_unicode_data():
    text = (MB / "unicode_data.h").read_text()
    out = [header("ext/mbstring/unicode_data.h")]
    for ctype, name, val in re.findall(r"static const ([a-z ]+?) +(\w+) = (\w+);", text):
        rtype = CTYPES[ctype.strip()]
        out.append(f"pub const {name.lstrip('_').upper()}: {rtype} = {parse_int(val)};\n")
    out.append("\n")
    for ctype, name, body in re.findall(r"static const ([a-z ]+?) +(\w+)\[\] = \{(.*?)\};", text, re.S):
        rtype = CTYPES[ctype.strip()]
        vals = [parse_int(v) for v in re.findall(r"-?(?:0[xX][0-9A-Fa-f]+|\d+)", body)]
        out.append(emit_array(name.lstrip("_").upper(), rtype, vals))
    (OUT / "unicode_data.rs").write_text("".join(out).rstrip("\n") + "\n")


def gen_eaw():
    text = (MB / "libmbfl/mbfl/eaw_table.h").read_text()
    pairs = re.findall(r"\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)\s*\}", text)
    first = re.search(r"#define FIRST_DOUBLEWIDTH_CODEPOINT (0x[0-9a-fA-F]+)", text).group(1)
    out = [header("ext/mbstring/libmbfl/mbfl/eaw_table.h")]
    out.append(f"/// First codepoint which may be double-width.\npub const FIRST_DOUBLEWIDTH_CODEPOINT: u32 = {first};\n\n")
    out.append("/// Ranges of double-width (East Asian Wide/Fullwidth) codepoints.\n#[rustfmt::skip]\n")
    out.append(f"pub static EAW_TABLE: [(u32, u32); {len(pairs)}] = [\n")
    for a, b in pairs:
        out.append(f"    ({a}, {b}),\n")
    out.append("];\n")
    (OUT / "eaw.rs").write_text("".join(out))


def gen_rare_cp():
    text = (MB / "rare_cp_bitvec.h").read_text()
    body = re.search(r"rare_codepoint_bitvec\[\] = \{(.*?)\};", text, re.S).group(1)
    vals = [parse_int(v) for v in re.findall(r"0x[0-9a-fA-F]+", body)]
    out = [header("ext/mbstring/rare_cp_bitvec.h")]
    out.append("/// One bit per codepoint U+0000-U+FFFF: set if 'rare' for encoding detection.\n")
    out.append(emit_array("RARE_CODEPOINT_BITVEC", "u32", vals))
    (OUT / "rare_cp.rs").write_text("".join(out).rstrip("\n") + "\n")


def gen_qencode():
    text = (MB / "libmbfl/filters/unicode_prop.h").read_text()
    body = re.search(r"mime_char_needs_qencode\[\] = \{(.*?)\};", text, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    vals = [int(v) for v in re.findall(r"\d+", body)]
    out = [header("ext/mbstring/libmbfl/filters/unicode_prop.h")]
    out.append("/// Whether an ASCII byte must be Q-encoded in a MIME encoded-word.\n")
    out.append("#[rustfmt::skip]\n")
    out.append(f"pub static MIME_CHAR_NEEDS_QENCODE: [u8; {len(vals)}] = [\n")
    for i in range(0, len(vals), 16):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",\n")
    out.append("];\n")
    (OUT / "qencode.rs").write_text("".join(out))


gen_qencode()
gen_unicode_data()
gen_eaw()
gen_rare_cp()
print("ok")

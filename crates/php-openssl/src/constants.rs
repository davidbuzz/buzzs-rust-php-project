#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn version_matches_linked_library() {
        assert!(openssl_version_text().starts_with("OpenSSL 3."));
        assert!(openssl_version_number() >= 0x3000_0000);
    }

    #[test]
    fn registration_list_is_unique() {
        let all = all();
        let mut names: Vec<_> = all.iter().map(|(n, _)| *n).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), all.len());
    }
}

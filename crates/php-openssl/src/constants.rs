/// `OPENSSL_VERSION_TEXT` of the linked library.
pub fn openssl_version_text() -> String {
    crate::ffi::version_text()
}

/// `OPENSSL_VERSION_NUMBER` of the linked library.
pub fn openssl_version_number() -> i64 {
    i64::try_from(crate::ffi::version_number()).unwrap_or(0)
}

/// A constant's value.

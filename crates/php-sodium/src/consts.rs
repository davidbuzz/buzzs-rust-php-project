/// `SODIUM_LIBRARY_VERSION` (`sodium_version_string()`, e.g. `"1.0.18"`);
/// also the "libsodium library version" `phpinfo()` row.
pub fn library_version() -> String {
    crate::init();
    // SAFETY: returns a pointer to a static NUL-terminated string.
    unsafe { CStr::from_ptr(ffi::sodium_version_string()) }
        .to_string_lossy()
        .into_owned()
}

/// `SODIUM_LIBRARY_MAJOR_VERSION` (10 for 1.0.18).
pub fn library_major_version() -> i64 {
    // SAFETY: no preconditions.
    i64::from(unsafe { ffi::sodium_library_version_major() })
}

/// `SODIUM_LIBRARY_MINOR_VERSION` (3 for 1.0.18).
pub fn library_minor_version() -> i64 {
    // SAFETY: no preconditions.
    i64::from(unsafe { ffi::sodium_library_version_minor() })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_and_tables() {
        assert_eq!(library_version(), "1.0.18");
        assert_eq!(library_major_version(), 10);
        assert_eq!(library_minor_version(), 3);
        assert_eq!(INT_CONSTANTS.len(), 89);
        assert_eq!(
            INT_CONSTANTS[0],
            ("SODIUM_CRYPTO_AEAD_AES256GCM_KEYBYTES", 32)
        );
    }

    #[test]
    fn match_the_library() {
        // SAFETY: plain size queries.
        unsafe {
            assert_eq!(ffi::crypto_generichash_statebytes(), 384);
            assert_eq!(ffi::crypto_secretstream_xchacha20poly1305_statebytes(), 52);
        }
    }
}

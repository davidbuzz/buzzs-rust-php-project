use super::*;
use std::os::unix::fs::symlink;
use std::path::PathBuf;
use std::sync::atomic::{AtomicUsize, Ordering};

/// A temporary directory removed on drop.
struct TempDir(PathBuf);

impl TempDir {
    fn new() -> Self {
        static COUNTER: AtomicUsize = AtomicUsize::new(0);
        let n = COUNTER.fetch_add(1, Ordering::Relaxed);
        let path =
            std::env::temp_dir().join(format!("php-streams-glob-{}-{n}", std::process::id()));
        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(&path).unwrap();
        TempDir(path)
    }

    fn bytes(&self) -> Vec<u8> {
        self.0.as_os_str().as_bytes().to_vec()
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

/// The fixture tree built by the oracle generator script.
fn make_tree(root: &Path) {
    for d in ["dir1", "dir1/sub", "dir2", "emptydir", ".hiddendir"] {
        fs::create_dir_all(root.join(d)).unwrap();
    }
    for f in [
        "a.txt",
        "b.txt",
        "c.log",
        ".hidden",
        "dir1/x.txt",
        "dir1/y.php",
        "dir1/sub/z.txt",
        "dir2/w.txt",
        "[x].txt",
        "q?.txt",
        "star*file",
        "brace{a}",
        "Upper.TXT",
        "1num",
        "back\\slash",
        ".hiddendir/h.txt",
    ] {
        fs::write(root.join(f), b"").unwrap();
    }
    symlink("dir1", root.join("link_dir")).unwrap();
    symlink("a.txt", root.join("link_file")).unwrap();
    symlink("nonexistent", root.join("dangling")).unwrap();
}

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

fn flag(name: &str) -> i64 {
    i64::from(match name {
        "GLOB_BRACE" => GLOB_BRACE,
        "GLOB_MARK" => GLOB_MARK,
        "GLOB_NOSORT" => GLOB_NOSORT,
        "GLOB_NOCHECK" => GLOB_NOCHECK,
        "GLOB_NOESCAPE" => GLOB_NOESCAPE,
        "GLOB_ERR" => GLOB_ERR,
        "GLOB_ONLYDIR" => GLOB_ONLYDIR,
        other => panic!("unknown flag {other}"),
    })
}

/// Cases where php-src master's bundled `php_glob.c` differs from the glibc
/// glob used by the `/usr/bin/php` 8.3 oracle: (pattern, flags, master result).
const MASTER_OVERRIDES: &[(&str, &str, &[&str])] = &[
    // php_glob only appends '/' when the path does not already end in one.
    (
        "*/",
        "GLOB_MARK",
        &["dir1/", "dir2/", "emptydir/", "link_dir/"],
    ),
    // GLOB_NOCHECK returns the pattern with quoting backslashes removed.
    ("zz\\*", "GLOB_NOCHECK", &["zz*"]),
];

/// Oracle table generated by running `/usr/bin/php8.5` over the same tree with
/// relative patterns; here every pattern is prefixed with the absolute root
/// so the tests need not change the process working directory.
#[test]
fn oracle_table() {
    let tmp = TempDir::new();
    make_tree(&tmp.0);
    let mut prefix = tmp.bytes();
    prefix.push(b'/');

    let data = include_str!("../../tests/data/glob_oracle.txt");
    let mut checked = 0;
    for line in data.lines() {
        let mut parts = line.split('\t');
        let pattern = unhex(parts.next().unwrap());
        let flag_names = parts.next().unwrap();
        let result = parts.next().unwrap_or("");
        // "" and "{}" mean something else once prefixed with the root
        // directory; they are covered by `relative_special_patterns`.
        if pattern.is_empty() || pattern == b"{}" {
            continue;
        }
        let flags = flag_names
            .split('|')
            .filter(|s| !s.is_empty())
            .map(flag)
            .fold(0, |a, b| a | b);

        let override_ = MASTER_OVERRIDES
            .iter()
            .find(|(p, f, _)| p.as_bytes() == pattern.as_slice() && *f == flag_names);
        let expected: Option<Vec<Vec<u8>>> = if let Some((_, _, r)) = override_ {
            Some(r.iter().map(|s| s.as_bytes().to_vec()).collect())
        } else if result == "false" {
            None
        } else if result.is_empty() {
            Some(Vec::new())
        } else {
            Some(result.split(',').map(unhex).collect())
        };

        let mut full = prefix.clone();
        full.extend_from_slice(&pattern);
        let got = glob(&full, flags).ok().map(|paths| {
            paths
                .into_iter()
                .map(|p| {
                    assert!(p.starts_with(&prefix), "{p:?}");
                    p[prefix.len()..].to_vec()
                })
                .collect::<Vec<_>>()
        });
        let show = |v: &Option<Vec<Vec<u8>>>| {
            v.as_ref().map(|v| {
                v.iter()
                    .map(|s| String::from_utf8_lossy(s).into_owned())
                    .collect::<Vec<_>>()
            })
        };
        assert_eq!(
            show(&got),
            show(&expected),
            "glob({:?}, {flag_names})",
            String::from_utf8_lossy(&pattern)
        );
        checked += 1;
    }
    assert_eq!(checked, data.lines().count() - 2);
}

#[test]
fn php_function_checks() {
    let long = vec![b'a'; MAXPATHLEN];
    let err = glob(&long, 0).unwrap_err();
    assert_eq!(err, GlobCallError::PatternTooLong);
    assert_eq!(
        err.warning().unwrap(),
        "Pattern exceeds the maximum allowed length of 4096 characters"
    );
    let err = glob(b"*", 0x0002).unwrap_err();
    assert_eq!(err, GlobCallError::InvalidFlags);
    assert_eq!(
        err.warning().unwrap(),
        "At least one of the passed flags is invalid or not supported on this platform"
    );
    assert_eq!(glob(b"", 0), Ok(Vec::new()));
    assert_eq!(
        GLOB_AVAILABLE_FLAGS,
        0x80 | 0x08 | 0x20 | 0x10 | 0x1000 | 0x04 | (1 << 30)
    );
}

#[test]
fn basedir_filter() {
    let tmp = TempDir::new();
    make_tree(&tmp.0);
    let mut pat = tmp.bytes();
    pat.extend_from_slice(b"/*.txt");
    // Everything rejected -> false.
    assert_eq!(
        glob_with_basedir(&pat, 0, |_| false),
        Err(GlobCallError::BasedirRestricted)
    );
    // Partially rejected -> the rest.
    let got = glob_with_basedir(&pat, 0, |p| p.ends_with(b"a.txt")).unwrap();
    assert_eq!(got.len(), 1);
    // No matches at all is still an empty array.
    let mut none = tmp.bytes();
    none.extend_from_slice(b"/nomatch*");
    assert_eq!(glob_with_basedir(&none, 0, |_| false), Ok(Vec::new()));
}

#[test]
fn low_level_codes() {
    let tmp = TempDir::new();
    make_tree(&tmp.0);
    let mut pat = tmp.bytes();
    pat.extend_from_slice(b"/nomatch*");
    assert_eq!(php_glob(&pat, 0), Err(GlobError::NoMatch));
    assert_eq!(GlobError::NoMatch.code(), -3);
    // Invalid character class: NOMATCH without GLOB_NOCHECK...
    let mut pat = tmp.bytes();
    pat.extend_from_slice(b"/[[:bogus:]]*");
    assert_eq!(php_glob(&pat, 0), Err(GlobError::NoMatch));
    // ...and the pattern itself with it.
    assert_eq!(php_glob(&pat, GLOB_NOCHECK), Ok(vec![pat.clone()]));
    // Unbalanced brace: only the prefix before the brace is globbed.
    let mut pat = tmp.bytes();
    pat.extend_from_slice(b"/{a,b");
    let mut prefix = tmp.bytes();
    prefix.push(b'/');
    assert_eq!(php_glob(&pat, GLOB_BRACE), Ok(vec![prefix]));
}

#[test]
fn relative_special_patterns() {
    // A lone "{}" is protected from brace expansion (globbed literally).
    let mut g = Globber {
        flags: GLOB_BRACE,
        pathv: Vec::new(),
    };
    assert_eq!(
        g.globexp1(&[LBRACE, RBRACE]),
        GlobError::NoMatch.code(),
        "assumes no file named {{}} in the test's working directory"
    );
    assert_eq!(php_glob(b"", 0), Err(GlobError::NoMatch));
    assert_eq!(php_glob(b"", GLOB_NOCHECK), Ok(vec![Vec::new()]));
}

#[test]
fn nosort_returns_all_entries() {
    let tmp = TempDir::new();
    make_tree(&tmp.0);
    let mut pat = tmp.bytes();
    pat.extend_from_slice(b"/*");
    let mut sorted = glob(&pat, 0).unwrap();
    let mut unsorted = glob(&pat, i64::from(GLOB_NOSORT)).unwrap();
    unsorted.sort();
    sorted.sort();
    assert_eq!(sorted, unsorted);
}

#[test]
fn matcher() {
    let compile = |p: &[u8]| -> Vec<Char> {
        // Reuse glob0's compiler through a pattern that cannot touch the
        // filesystem: compile manually for the simple cases below.
        p.iter()
            .map(|&b| match b {
                b'*' => M_ALL,
                b'?' => M_ONE,
                _ => Char::from(b),
            })
            .collect()
    };
    let name = |s: &[u8]| s.iter().map(|&b| Char::from(b)).collect::<Vec<_>>();
    assert!(glob_match(&name(b"abc"), &compile(b"a*")));
    assert!(glob_match(&name(b"abc"), &compile(b"*c")));
    assert!(glob_match(&name(b"abc"), &compile(b"a?c")));
    assert!(!glob_match(&name(b"abc"), &compile(b"a?d")));
    assert!(glob_match(&name(b""), &compile(b"*")));
    let long = name(&[b'a'; 100]);
    assert!(!glob_match(&long, &compile(b"a*a*a*a*a*a*a*y")));
}
